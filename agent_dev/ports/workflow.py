from typing import Protocol

from agent_dev.domain.contracts import PhaseRequest, PhaseResult, TaskRecord
from agent_dev.domain.status import TaskStatus
from agent_dev.domain.transitions import TransitionContext


class RunnerPort(Protocol):
    def execute(self, request: PhaseRequest) -> PhaseResult: ...


class WorkflowStore(Protocol):
    def assert_change_allowed(self, task_id: str, connection=None) -> dict: ...
    def task(self, task_id: str) -> TaskRecord: ...
    def snapshot(self, task_id: str) -> dict: ...
    def transition(
        self,
        task_id: str,
        target: TaskStatus,
        context: TransitionContext,
        lease: dict | None = None,
    ) -> TaskRecord: ...
    def dependencies_complete(self, task_id: str) -> bool: ...
    def approved(self, task_id: str) -> bool: ...
    def event(self, aggregate_id: str, kind: str, payload: dict) -> str: ...
    def begin_attempt(self, task_id: str, phase_id: str, key: str, lease: dict) -> dict: ...
    def finish_attempt(self, attempt_id: str, state: str, lease: dict) -> None: ...
    def passed_attempt(self, task_id: str, phase_id: str, generation: int) -> dict | None: ...
    def generation(self, task_id: str) -> int: ...
    def node_runs(self, task_id, generation=None) -> dict: ...
    def record_node(
        self,
        task_id,
        node_id,
        generation,
        state,
        input_digest,
        result,
        lease,
        expected_version=None,
    ) -> dict: ...
    def execution_usage(self, task_id: str) -> dict: ...
    def recover_attempts(self, task_id: str, lease: dict) -> None: ...
    def reenter(
        self, task_id: str, phase_ids: list[str], fingerprint: str, max_reentries: int, lease: dict
    ) -> int: ...


class ArtifactPort(Protocol):
    def prompt(self, task_id: str, phase_id: str, attempt_id: str, content: str) -> str: ...
    def write(self, task_id: str, phase_id: str, attempt_id: str, content: str) -> str: ...
    def context(self, task_id: str, phase_id: str) -> str: ...


class PhaseCatalogPort(Protocol):
    def phases(self, task: TaskRecord) -> list[tuple[str, frozenset[str]]]: ...
    def preflight(self, task: TaskRecord) -> bool: ...
    def verify_node(self, task_id, gate_ids, lease) -> dict: ...
    def role_before(self, task_id, node_id) -> dict: ...
    def enforce_session(self, task_id, node_ids, before, declared=None) -> dict: ...
    def apply_role_result(
        self, task_id, node_id, output, before=None, lease=None, generation=None
    ) -> None: ...
